/**
 * A minimal next-auth v4 credentials look-alike on 127.0.0.1 for strategy tests.
 *
 * Routes: GET /api/auth/csrf, POST /api/auth/callback/credentials, GET /api/auth/session,
 * and with `rotateEndpoint: true` PUT/POST /api/admin/password (JSON { email, password },
 * needs the session cookie of a user with role "Administrator").
 * With `handoff`: GET /api/auth/agent-handoff?code=<code>, a reference agent handoff
 * route per docs/HANDOFF-ROUTE-CONTRACT.md (mirrors examples/demo-app's): the code is
 * checked with the reference verifier, the nonce burned, a session minted exactly as
 * the credentials callback would, and the answer is 302 Location "/"; every failure is
 * a bare 404.
 * Credentials are supplied by the test (generated at test time); nothing is logged.
 */
import { createHash, randomBytes } from "node:crypto";
import http from "node:http";
import type { AddressInfo } from "node:net";
import { MemoryNonceStore, verifyHandoffCode } from "../../src/handoff.js";

export interface FakeUser {
  email: string;
  password: string;
  name?: string;
  role?: string;
  /** App permissions (e.g. "EXCHANGE_ACCESS"), visible to extraRoutes via sessionUserFor. */
  permissions?: string[];
}

/** Helpers handed to FakeNextAuthOptions.extraRoutes. */
export interface FakeNextAuthRouteContext {
  /** The signed-in user for a request's Cookie header, or undefined. */
  sessionUserFor(cookieHeader: string | undefined): FakeUser | undefined;
}

/** The reference agent handoff route (see the module comment). Knobs stage broken routes. */
export interface FakeHandoffRoute {
  /** The deployment's AGENT_HANDOFF_SECRET (generated by the test). */
  secret: string;
  /** The app's own profile map: app-handoff profile name -> account email. */
  profiles: Record<string, string>;
  /** Route path; default "/api/auth/agent-handoff". */
  path?: string;
  /** After a valid code, answer this status instead of the contract's 302 (the session is still minted). */
  status?: number;
  /** Location of the redirect; default "/". */
  location?: string;
  /** Answer a valid code without setting the session cookie. */
  noCookie?: boolean;
  /** Add `Domain=<value>` to the session cookie. */
  cookieDomain?: string;
  /** Session cookie lifetime in seconds; default: the fake's session max age. */
  maxAgeSeconds?: number;
  /** Extra Set-Cookie values sent with a successful answer. */
  extraCookies?: string[];
}

export interface FakeNextAuthOptions {
  users: FakeUser[];
  /** Serve the reference agent handoff route. */
  handoff?: FakeHandoffRoute;
  /** Use __Secure-/__Host- cookie names with the Secure flag (next-auth on https). */
  secureCookie?: boolean;
  /** GET /api/auth/csrf responds 500. */
  failCsrf?: boolean;
  /** Session cookie Max-Age; defaults to next-auth's 30 days. */
  sessionMaxAgeSeconds?: number;
  /** Include `role` in the /api/auth/session user object. */
  includeRoleInSession?: boolean;
  /** Answer the callback with a 302 + Location instead of 200 { url } (the non-json shape). */
  respondWithRedirect?: boolean;
  /**
   * Serve PUT/POST /api/admin/password: JSON { email, password } sets that user's
   * password. Requires the session cookie of a user whose role is "Administrator"
   * (401 without a session, 403 for another role).
   */
  rotateEndpoint?: boolean;
  /** With rotateEndpoint: after the admin check, answer this status without applying the change. */
  rotateFailStatus?: number;
  /** With rotateEndpoint: answer 200 without applying the change (a buggy app). */
  rotateIgnore?: boolean;
  /** With rotateEndpoint: apply the change, then answer this status anyway (another buggy app). */
  rotateStatusAfterApply?: number;
  /** With rotateEndpoint: answer 200 at once but apply the change only after this many ms (eventual consistency). */
  rotateApplyDelayMs?: number;
  /**
   * Extra routes on the same origin (e.g. the service exchange API). Called for any
   * request the built-in routes do not handle; resolve true when handled.
   */
  extraRoutes?: (
    req: http.IncomingMessage,
    res: http.ServerResponse,
    url: URL,
    ctx: FakeNextAuthRouteContext,
  ) => Promise<boolean> | boolean;
}

export interface FakeRequest {
  method: string;
  path: string;
  hasCsrfCookie: boolean;
}

export interface FakeNextAuth {
  baseUrl: string;
  close(): Promise<void>;
  requests: FakeRequest[];
  /** The signed-in user for a Cookie header, or undefined (same as the extraRoutes helper). */
  sessionUserFor(cookieHeader: string | undefined): FakeUser | undefined;
  /** Change a user's password (as an admin would in the app). Existing sessions stay valid. */
  setPassword(email: string, password: string): void;
  /** Number of passwords the rotate endpoint actually changed. */
  readonly passwordChanges: number;
  /**
   * Every handoff code the route received, in order (kept in memory for leak
   * assertions only; never logged).
   */
  handoffCodes: string[];
  /** Outcome per handoff request: "ok" or the refusal reason. */
  handoffOutcomes: string[];
  /** Every session token the fake minted (credentials or handoff), for leak assertions. */
  sessionTokens: string[];
}

function parseCookies(header: string | undefined): Map<string, string> {
  const out = new Map<string, string>();
  if (!header) return out;
  for (const part of header.split(";")) {
    const i = part.indexOf("=");
    if (i === -1) continue;
    out.set(part.slice(0, i).trim(), part.slice(i + 1).trim());
  }
  return out;
}

async function readBody(req: http.IncomingMessage): Promise<string> {
  const chunks: Buffer[] = [];
  for await (const chunk of req) chunks.push(chunk as Buffer);
  return Buffer.concat(chunks).toString("utf8");
}

export async function startFakeNextAuth(opts: FakeNextAuthOptions): Promise<FakeNextAuth> {
  const serverSecret = randomBytes(16).toString("hex");
  const secure = opts.secureCookie === true;
  const csrfCookieName = secure ? "__Host-next-auth.csrf-token" : "next-auth.csrf-token";
  const callbackCookieName = secure ? "__Secure-next-auth.callback-url" : "next-auth.callback-url";
  const sessionCookieName = secure ? "__Secure-next-auth.session-token" : "next-auth.session-token";
  const secureAttr = secure ? "; Secure" : "";
  const maxAge = opts.sessionMaxAgeSeconds ?? 30 * 24 * 60 * 60;
  const sessions = new Map<string, FakeUser>();
  const sessionTokens: string[] = [];
  const handoffCodes: string[] = [];
  const handoffOutcomes: string[] = [];
  const handoffNonces = new MemoryNonceStore();
  const requests: FakeRequest[] = [];
  let baseUrl = "";
  let passwordChanges = 0;

  const sessionUserFor = (header: string | undefined): FakeUser | undefined =>
    sessions.get(parseCookies(header).get(sessionCookieName) ?? "");

  const csrfHash = (token: string): string =>
    createHash("sha256").update(`${token}${serverSecret}`).digest("hex");

  const json = (res: http.ServerResponse, status: number, body: unknown, cookies: string[] = []): void => {
    if (cookies.length > 0) res.setHeader("Set-Cookie", cookies);
    res.writeHead(status, { "Content-Type": "application/json" });
    res.end(JSON.stringify(body));
  };

  const server = http.createServer((req, res) => {
    void (async () => {
      const url = new URL(req.url ?? "/", baseUrl);
      const cookies = parseCookies(req.headers.cookie);
      requests.push({ method: req.method ?? "", path: url.pathname, hasCsrfCookie: cookies.has(csrfCookieName) });

      if (req.method === "GET" && url.pathname === "/api/auth/csrf") {
        if (opts.failCsrf) return json(res, 500, { message: "Internal Server Error" });
        const token = randomBytes(32).toString("hex");
        return json(res, 200, { csrfToken: token }, [
          `${csrfCookieName}=${token}%7C${csrfHash(token)}; Path=/; HttpOnly; SameSite=Lax${secureAttr}`,
          `${callbackCookieName}=${encodeURIComponent(baseUrl)}; Path=/; SameSite=Lax${secureAttr}`,
        ]);
      }

      if (req.method === "POST" && url.pathname === "/api/auth/callback/credentials") {
        const form = new URLSearchParams(await readBody(req));
        const respond = (target: string, setCookies: string[] = []): void => {
          if (opts.respondWithRedirect || form.get("json") !== "true") {
            if (setCookies.length > 0) res.setHeader("Set-Cookie", setCookies);
            res.writeHead(302, { Location: target });
            res.end();
            return;
          }
          json(res, 200, { url: target }, setCookies);
        };

        const rawCsrf = decodeURIComponent(cookies.get(csrfCookieName) ?? "");
        const [cookieToken, cookieHash] = rawCsrf.split("|");
        const posted = form.get("csrfToken");
        const csrfOk =
          cookieToken !== undefined &&
          cookieToken !== "" &&
          cookieHash === csrfHash(cookieToken) &&
          posted === cookieToken;
        if (!csrfOk) return respond(`${baseUrl}/api/auth/error?error=MissingCSRF`);

        const user = opts.users.find(
          (u) => u.email === form.get("email") && u.password === form.get("password"),
        );
        if (!user) return respond(`${baseUrl}/api/auth/error?error=CredentialsSignin`);

        const token = randomBytes(32).toString("hex");
        sessions.set(token, user);
        sessionTokens.push(token);
        const expires = new Date(Date.now() + maxAge * 1000).toUTCString();
        return respond(form.get("callbackUrl") ?? baseUrl, [
          `${sessionCookieName}=${token}; Path=/; Expires=${expires}; Max-Age=${maxAge}; HttpOnly; SameSite=Lax${secureAttr}`,
        ]);
      }

      if (req.method === "GET" && url.pathname === "/api/auth/session") {
        const user = sessions.get(cookies.get(sessionCookieName) ?? "");
        if (!user) return json(res, 200, {});
        const sessionUser: Record<string, unknown> = {
          name: user.name ?? "Test User",
          email: user.email,
          userId: "user_1",
          tenantId: "tenant_1",
          tenantSlug: "test-tenant",
          isServiceAccount: false,
        };
        if (opts.includeRoleInSession && user.role !== undefined) sessionUser["role"] = user.role;
        return json(res, 200, {
          user: sessionUser,
          expires: new Date(Date.now() + maxAge * 1000).toISOString(),
        });
      }

      const handoff = opts.handoff;
      if (handoff !== undefined && url.pathname === (handoff.path ?? "/api/auth/agent-handoff")) {
        const refuse = (reason: string): void => {
          handoffOutcomes.push(reason);
          res.writeHead(404, { "Cache-Control": "no-store" });
          res.end();
        };
        // HEAD would burn the nonce if it ran GET; the contract route answers it with 404.
        if (req.method !== "GET") return refuse("method");
        const code = url.searchParams.get("code");
        if (code === null) return refuse("malformed");
        handoffCodes.push(code);
        const result = await verifyHandoffCode({ code, secret: handoff.secret, nonceStore: handoffNonces });
        if (!result.ok) return refuse(result.reason);
        const email = Object.hasOwn(handoff.profiles, result.profileName)
          ? handoff.profiles[result.profileName]
          : undefined;
        if (email === undefined) return refuse("unknown profile");
        const user = opts.users.find((u) => u.email === email);
        if (user === undefined) return refuse("unknown user");

        const token = randomBytes(32).toString("hex");
        sessions.set(token, user);
        sessionTokens.push(token);
        const age = handoff.maxAgeSeconds ?? maxAge;
        const domain = handoff.cookieDomain !== undefined ? `; Domain=${handoff.cookieDomain}` : "";
        const setCookies =
          handoff.noCookie === true
            ? []
            : [
                `${sessionCookieName}=${token}; Path=/; Expires=${new Date(Date.now() + age * 1000).toUTCString()}; ` +
                  `Max-Age=${age}; HttpOnly; SameSite=Lax${secureAttr}${domain}`,
              ];
        setCookies.push(...(handoff.extraCookies ?? []));
        handoffOutcomes.push("ok");
        if (setCookies.length > 0) res.setHeader("Set-Cookie", setCookies);
        res.writeHead(handoff.status ?? 302, {
          Location: handoff.location ?? "/",
          "Cache-Control": "no-store",
          "Referrer-Policy": "no-referrer",
        });
        res.end();
        return;
      }

      if (
        opts.rotateEndpoint === true &&
        (req.method === "PUT" || req.method === "POST") &&
        url.pathname === "/api/admin/password"
      ) {
        const caller = sessions.get(cookies.get(sessionCookieName) ?? "");
        if (caller === undefined) return json(res, 401, { error: "unauthorized" });
        if (caller.role !== "Administrator") return json(res, 403, { error: "forbidden" });
        if (opts.rotateFailStatus !== undefined) return json(res, opts.rotateFailStatus, { error: "rotation failed" });
        if (!(req.headers["content-type"] ?? "").startsWith("application/json")) {
          return json(res, 415, { error: "json only" });
        }
        let body: unknown;
        try {
          body = JSON.parse(await readBody(req));
        } catch {
          return json(res, 400, { error: "bad json" });
        }
        const rec = (body ?? {}) as Record<string, unknown>;
        const target = opts.users.find((u) => u.email === rec["email"]);
        if (target === undefined) return json(res, 404, { error: "no such user" });
        if (typeof rec["password"] !== "string" || rec["password"].length < 12) {
          return json(res, 400, { error: "weak password" });
        }
        const next = rec["password"];
        if (opts.rotateApplyDelayMs !== undefined) {
          setTimeout(() => {
            target.password = next;
            passwordChanges += 1;
          }, opts.rotateApplyDelayMs).unref();
        } else if (opts.rotateIgnore !== true) {
          target.password = next;
          passwordChanges += 1;
        }
        return json(res, opts.rotateStatusAfterApply ?? 200, { ok: true });
      }

      if (opts.extraRoutes !== undefined) {
        const routeCtx: FakeNextAuthRouteContext = { sessionUserFor };
        if (await opts.extraRoutes(req, res, url, routeCtx)) return;
      }

      json(res, 404, { error: "not found" });
    })().catch(() => {
      if (!res.headersSent) res.writeHead(500);
      res.end();
    });
  });

  await new Promise<void>((resolve) => server.listen(0, "127.0.0.1", resolve));
  const { port } = server.address() as AddressInfo;
  baseUrl = `http://127.0.0.1:${port}`;

  return {
    baseUrl,
    requests,
    sessionUserFor,
    setPassword: (email: string, password: string): void => {
      const user = opts.users.find((u) => u.email === email);
      if (user === undefined) throw new Error("fake: no such user");
      user.password = password;
    },
    get passwordChanges(): number {
      return passwordChanges;
    },
    handoffCodes,
    handoffOutcomes,
    sessionTokens,
    close: () =>
      new Promise<void>((resolve, reject) => {
        server.closeAllConnections();
        server.close((err) => (err ? reject(err) : resolve()));
      }),
  };
}
